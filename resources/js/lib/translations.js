export function resolveTranslation(locale, key, fallback = key) {
  const selectedLanguage = supportedLanguages.includes(locale) ? locale : 'en';
  const keys = key.split('.');
  let current = translations[selectedLanguage];

  for (const segment of keys) {
    if (!current || typeof current !== 'object') {
      return fallback;
    }
    current = current[segment];
  }

  return current ?? fallback;
}

export function useTranslation() {
  if (typeof window !== 'undefined') {
    const storedLanguage = localStorage.getItem('language');
    const selectedLanguage = supportedLanguages.includes(storedLanguage) ? storedLanguage : 'en';

    return {
      locale: selectedLanguage,
      t: (key, fallback) => resolveTranslation(selectedLanguage, key, fallback ?? key),
    };
  }

  return {
    locale: 'en',
    t: (key, fallback) => resolveTranslation('en', key, fallback ?? key),
  };
}
